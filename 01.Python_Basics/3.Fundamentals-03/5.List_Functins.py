# List specific functions(which is only use in the list functions)

nums = [5,6,7,8,3,5,6]

nums.append(100) #append() --> add element at the end
nums.insert(2,10) #insert(idx,val) - > insert element at some index posiotn
nums.sort()     #arrange in ascending order
nums.sort(reverse=True)  # arrange in descending order
nums.reverse()   #reverse the entire list
print(nums)


